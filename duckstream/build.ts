import {
  checkCompiledProgram,
  compileProgram,
} from "@bonisoft3/pronto/duckstream/compiler.ts";
import { translatePhysical } from "@bonisoft3/pronto/duckstream/translator.ts";
import {
  carriers,
  type Computation,
  descriptor,
  outputs,
  physicalCarriers,
} from "./carriers.ts";
const here = new URL("./", import.meta.url);
export async function build(name: Computation, compile = false) {
  const options = {
    sourcePath: new URL(name + ".sql", here).pathname,
    outputDirectory: new URL(name + "/", here).pathname,
    views: outputs[name].map((o) => "result_" + o),
  };
  if (compile) {
    await compileProgram(options);
  }
  const compiled = await checkCompiledProgram(options);
  const queries = carriers(name, compiled.queries, compiled.schema);
  const queryStages = physicalCarriers(
    name,
    Object.fromEntries(outputs[name].map((output) => [
      "result_" + output,
      translatePhysical(
        compiled.source,
        compiled.schema,
        "result_" + output,
        `__duckstream_${name}_${output}`,
      ),
    ])),
    compiled.schema,
  );
  const reads = compiled.schema.inputs.map((r) =>
    r.name.replace(/^source_/, "")
  );
  const pure = await Deno.readTextFile(new URL(name + ".pure.js", here));
  const order = (await Deno.readTextFile(new URL("order.js", here))).replace(
    "export const ordered",
    "const ordered",
  );
  const source = [
    "// Generated by duckstream/build.ts from Duckstream SQL and the pure numerical program.",
    "export const reads = " + JSON.stringify(reads) + ";",
    "export const queries = " + JSON.stringify(queries, null, 2) + ";",
    "export const queryStages = " + JSON.stringify(queryStages, null, 2) + ";",
    order,
    pure.replaceAll(/^export const /gm, "const ")
      .replace("const plan", "const numericalPlan")
      .replace("const finish", "const numericalFinish"),
    `export const plan = (inputs, ...args) => numericalPlan(ordered(${
      JSON.stringify(name)
    }, inputs), ...args);`,
    `export const finish = (inputs, ...args) => numericalFinish(ordered(${
      JSON.stringify(name)
    }, inputs), ...args);`,
  ].join("\n") + "\n";
  const risingwave = JSON.stringify(
    descriptor(
      name,
      await Deno.readTextFile(options.sourcePath),
      compiled.schema,
    ),
    null,
    2,
  ) + "\n";
  return { source, risingwave };
}
if (import.meta.main) {
  const only = Deno.args.find((arg) => arg.startsWith("--only="))?.slice(7)
    .split(",");
  if (only?.some((name) => !(name in outputs))) {
    throw new Error("unknown computation selector");
  }
  for (const name of Object.keys(outputs) as Computation[]) {
    if (only && !only.includes(name)) continue;
    const { source, risingwave } = await build(
      name,
      Deno.args.includes("--compile"),
    );
    for (
      const [path, value] of [[`../computations/${name}.js`, source], [
        `${name}.risingwave.json`,
        risingwave,
      ]]
    ) {
      const url = new URL(path, here);
      if (Deno.args.includes("--check")) {
        if (await Deno.readTextFile(url) !== value) {
          throw new Error(path + " differs; run duckstream/build.ts");
        }
      } else await Deno.writeTextFile(url, value);
    }
  }
}
